CREATE TABLE Atomo (
    Simbolo       VARCHAR(3)    NOT NULL,
    Nome          VARCHAR(50)   NOT NULL,
    NumeroAtomico INT           NOT NULL,
    MassaAtomica  DECIMAL(10,6) NOT NULL,
    Camada        CHAR(1)       NOT NULL,
    Grupo         INT           NOT NULL,
    Familia       VARCHAR(50)   NOT NULL,

    Eletrons AS NumeroAtomico,
    Protons  AS NumeroAtomico,
    Neutrons AS CAST(ROUND(MassaAtomica,0) AS INT) - NumeroAtomico,

    CONSTRAINT PK_Atomo PRIMARY KEY NONCLUSTERED (Simbolo)
);
GO

CREATE CLUSTERED INDEX IX_Atomo_NumeroAtomico
ON Atomo (NumeroAtomico);
GO

